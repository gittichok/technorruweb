export function t(lang: Lang, key: UiKey): string {
  return ui[lang][key] ?? ui.th[key];
}

/** เส้นทางของหน้าในภาษาที่กำหนด: path('en', '/programs') -> '/en/programs' */
export function path(lang: Lang, p: string): string {
  const clean = p.startsWith('/') ? p : `/${p}`;
  if (lang === 'th') return clean;
  return clean === '/' ? '/en/' : `/en${clean}`;
}

/** ข้อความสองภาษาจากไฟล์ข้อมูล ({ th, en }) ถ้าไม่มีภาษาอังกฤษจะแสดงภาษาไทย */
export function pick(value: { th?: string; en?: string } | string | undefined, lang: Lang): string {
  if (!value) return '';
  if (typeof value === 'string') return value;
  return (lang === 'en' ? value.en : value.th) || value.th || '';
}
